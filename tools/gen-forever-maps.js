#!/usr/bin/env node
// Generates AchievementsForeverData/AchievementsForeverData_ForeverMaps.lua from
// the WoW Forever client's own map tables on wago.tools.
//
//   node tools/gen-forever-maps.js [--build 1.60.1.70374] [--offline]
//
// Why this exists: the achievement data this addon ships comes from Wrath
// Classic 3.4.5, and its exploration criteria point at WorldMapOverlay rows of
// that client. The Forever client re-cut every zone map (new UiMapArt rows,
// new WorldMapOverlay rows, new IDs), so C_MapExplorationInfo never reports a
// piece that matches a Wrath row. Each overlay row carries the AreaID it
// reveals, though, and the area IDs did not change. This script therefore
// writes:
//   - every Forever WorldMapOverlay row (merged over the Wrath rows),
//   - the Forever UiMap list (so the explored-map scan covers Forever's maps),
//   - worldMapOverlayEquivalents: Wrath overlay ID -> Forever overlay IDs that
//     reveal the same area on a live Forever map.
//
// CSVs are cached under tools/.cache/forever-db2/<build>/ so re-runs are offline.

const fs = require('fs');
const path = require('path');

const args = process.argv.slice(2);
function arg(name, def) { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : def; }
const BUILD = arg('--build', '1.60.1.70374');
const OFFLINE = args.includes('--offline');

const repoRoot = path.resolve(__dirname, '..');
const cacheDir = path.join(__dirname, '.cache', 'forever-db2', BUILD);
const outFile = path.join(repoRoot, 'AchievementsForeverData', 'AchievementsForeverData_ForeverMaps.lua');
const TABLES = ['WorldMapOverlay', 'UiMapXMapArt', 'UiMap', 'AreaTable'];

function parseCsv(text) {
  const rows = [];
  let row = [], field = '', inQ = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQ) {
      if (c === '"') { if (text[i + 1] === '"') { field += '"'; i++; } else inQ = false; }
      else field += c;
    } else if (c === '"') inQ = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n') { row.push(field); rows.push(row); row = []; field = ''; }
    else if (c !== '\r') field += c;
  }
  if (field !== '' || row.length) { row.push(field); rows.push(row); }
  const header = rows.shift();
  return rows.filter(r => r.length === header.length).map(r => Object.fromEntries(header.map((h, i) => [h, r[i]])));
}

async function loadTable(name) {
  const file = path.join(cacheDir, name + '.csv');
  if (!fs.existsSync(file)) {
    if (OFFLINE) throw new Error(`missing cached ${file} and --offline was given`);
    const url = `https://wago.tools/db2/${name}/csv?build=${BUILD}`;
    process.stdout.write(`downloading ${url} ... `);
    const res = await fetch(url);
    if (!res.ok) throw new Error(`${url} -> HTTP ${res.status}`);
    const text = await res.text();
    if (!text.startsWith('ID,') && !text.includes(',ID,')) throw new Error(`${url} did not return a CSV`);
    fs.mkdirSync(cacheDir, { recursive: true });
    fs.writeFileSync(file, text, 'utf8');
    console.log(`${text.length} bytes`);
  }
  return parseCsv(fs.readFileSync(file, 'utf8'));
}

function luaString(s) {
  return '"' + String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\r?\n/g, '\\n') + '"';
}

(async () => {
  const [overlays, uiMapXMapArt, uiMaps, areas] = await Promise.all(TABLES.map(loadTable));
  const areaName = Object.fromEntries(areas.map(a => [a.ID, a.AreaName_lang]));

  // Forever shows exactly one art per map; those art IDs are the "live" ones.
  const liveArt = new Set(uiMapXMapArt.map(x => x.UiMapArtID));
  const liveMapByArt = Object.fromEntries(uiMapXMapArt.map(x => [x.UiMapArtID, x.UiMapID]));

  const byArea = {};
  for (const o of overlays) {
    if (o.AreaID_0 !== '0') (byArea[o.AreaID_0] = byArea[o.AreaID_0] || []).push(o);
  }

  const equivalents = {};
  let bridged = 0, unbridged = [];
  for (const o of overlays) {
    if (liveArt.has(o.UiMapArtID) || o.AreaID_0 === '0') continue;
    const live = (byArea[o.AreaID_0] || []).filter(x => x.ID !== o.ID && liveArt.has(x.UiMapArtID));
    if (live.length) { equivalents[o.ID] = live.map(x => Number(x.ID)); bridged++; }
    else unbridged.push(`${o.ID} (${areaName[o.AreaID_0] || o.AreaID_0})`);
  }

  const out = [];
  out.push(`-- AchievementsForeverData_ForeverMaps.lua`);
  out.push(`-- Generated by tools/gen-forever-maps.js from the WoW Forever client's map`);
  out.push(`-- tables (wago.tools, build ${BUILD}). Do not edit by hand.`);
  out.push(`--`);
  out.push(`-- Loads after AchievementsForeverData_Classic.lua and merges Forever's`);
  out.push(`-- WorldMapOverlay rows and UiMap list into the shared data table. The`);
  out.push(`-- Wrath exploration criteria keep their original overlay IDs; the`);
  out.push(`-- equivalents table maps each of them to the Forever overlay rows that`);
  out.push(`-- reveal the same area on the re-cut Forever maps.`);
  out.push(``);
  out.push(`local data = AchievementsForeverData;`);
  out.push(`data.foreverMapsBuild = ${luaString(BUILD)};`);
  out.push(``);
  out.push(`-- id, uiMapArtID, textureWidth, textureHeight, offsetX, offsetY, hitRectTop, hitRectBottom, hitRectLeft, hitRectRight, areaID`);
  out.push(`local overlayRows = {`);
  for (const o of overlays.sort((a, b) => Number(a.ID) - Number(b.ID))) {
    out.push(`\t{ ${[o.ID, o.UiMapArtID, o.TextureWidth, o.TextureHeight, o.OffsetX, o.OffsetY, o.HitRectTop, o.HitRectBottom, o.HitRectLeft, o.HitRectRight, o.AreaID_0].join(', ')} },`);
  }
  out.push(`};`);
  out.push(``);
  out.push(`data.worldMapOverlays = data.worldMapOverlays or {};`);
  out.push(`for _, row in ipairs(overlayRows) do`);
  out.push(`\tdata.worldMapOverlays[row[1]] = {`);
  out.push(`\t\tid = row[1], uiMapArtID = row[2], textureWidth = row[3], textureHeight = row[4],`);
  out.push(`\t\toffsetX = row[5], offsetY = row[6], hitRectTop = row[7], hitRectBottom = row[8],`);
  out.push(`\t\thitRectLeft = row[9], hitRectRight = row[10], areaID = row[11],`);
  out.push(`\t};`);
  out.push(`end`);
  out.push(``);
  out.push(`data.uiMaps = data.uiMaps or {};`);
  out.push(`local foreverUiMaps = {`);
  for (const m of uiMaps.sort((a, b) => Number(a.ID) - Number(b.ID))) {
    out.push(`\t[${m.ID}] = ${luaString(m.Name_lang)},`);
  }
  out.push(`};`);
  out.push(`for uiMapID, name in pairs(foreverUiMaps) do`);
  out.push(`\tdata.uiMaps[uiMapID] = data.uiMaps[uiMapID] or { name = name };`);
  out.push(`end`);
  out.push(``);
  out.push(`-- live Forever map art -> uiMapID`);
  out.push(`data.foreverUiMapByArtID = {`);
  for (const [art, map] of Object.entries(liveMapByArt).sort((a, b) => Number(a[0]) - Number(b[0]))) out.push(`\t[${art}] = ${map},`);
  out.push(`};`);
  out.push(``);
  out.push(`-- Wrath overlay ID -> Forever overlay IDs revealing the same area`);
  out.push(`data.worldMapOverlayEquivalents = {`);
  for (const [id, list] of Object.entries(equivalents).sort((a, b) => Number(a[0]) - Number(b[0]))) out.push(`\t[${id}] = { ${list.join(', ')} },`);
  out.push(`};`);
  out.push(``);
  fs.writeFileSync(outFile, out.join('\n'), 'utf8');

  console.log(`overlay rows: ${overlays.length}, uiMaps: ${uiMaps.length}, live art IDs: ${liveArt.size}`);
  console.log(`old overlay rows bridged to a Forever row by area: ${bridged}; unbridged: ${unbridged.length}`);
  if (unbridged.length) console.log('  ' + unbridged.join(', '));
  console.log('wrote', path.relative(repoRoot, outFile));
})().catch(e => { console.error(e); process.exit(1); });
